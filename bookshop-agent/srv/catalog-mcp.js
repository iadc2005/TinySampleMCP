const cds = require('@sap/cds')

/**
 * Handler for CatalogMcpService.
 *
 * @cap-js/mcp exposes CAP entities only as read-only (query/describe) tools.
 * To let an MCP client (e.g. SAP Joule) create books, we expose a dedicated
 * unbound action `createBook`, which the adapter turns into a callable tool.
 */
module.exports = class CatalogMcpService extends cds.ApplicationService {
  init() {
    const { Books } = this.entities

    this.on('createBook', async (req) => {
      const { title, author, stock } = req.data

      if (!title) return req.reject(400, 'title is required')

      // ID is @Core.Computed (UUID) -> generated by CAP on INSERT.
      const created = await INSERT.into(Books).entries({ title, author, stock })
      // Return the freshly created row (including its generated ID).
      const id = created?.results?.[0]?.values?.[0] ?? created?.ID
      const row = id
        ? await SELECT.one.from(Books).where({ ID: id })
        : { title, author, stock }
      return row
    })

    return super.init()
  }
}
